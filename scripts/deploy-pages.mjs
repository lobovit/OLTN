#!/usr/bin/env node
/* Publishes the built site to https://oltnclient.github.io through the
   oltnclient/oltnclient.github.io repository (the source repo stays clean).
   Run via `make publish`; safe to re-run — skips the push when unchanged. */

import { execFileSync } from "node:child_process";
import { cpSync, existsSync, readdirSync, rmSync, writeFileSync } from "node:fs";

const REPO_URL = "https://github.com/oltnclient/oltnclient.github.io.git";
const SITE_URL = "https://oltnclient.github.io/";
const DEPLOY_DIR = ".deploy";
const BRANCH = "main";

/** Runs git inside the deploy clone; stdio inherits by default. */
function git(args, options = {}) {
  return execFileSync("git", ["-C", DEPLOY_DIR, ...args], { stdio: "inherit", ...options });
}

if (!existsSync("dist/index.html")) {
  console.error("dist/ not found — run `npm run build` first (or just `make publish`).");
  process.exit(1);
}

if (!existsSync(DEPLOY_DIR)) {
  console.log(`> cloning ${REPO_URL} into ${DEPLOY_DIR}`);
  execFileSync("git", ["clone", "--branch", BRANCH, REPO_URL, DEPLOY_DIR], { stdio: "inherit" });
} else {
  console.log(`> updating ${DEPLOY_DIR}`);
  git(["fetch", "origin", BRANCH]);
  git(["reset", "--hard", `origin/${BRANCH}`]);
}

console.log("> syncing dist/");
for (const entry of readdirSync(DEPLOY_DIR)) {
  if (entry === ".git") continue;
  rmSync(`${DEPLOY_DIR}/${entry}`, { recursive: true, force: true });
}
cpSync("dist", DEPLOY_DIR, { recursive: true });
writeFileSync(`${DEPLOY_DIR}/.nojekyll`, "");
writeFileSync(
  `${DEPLOY_DIR}/README.md`,
  [
    "# oltnclient.github.io",
    "",
    "Built site of **OLTN** — another Mastodon web client.",
    "Source: https://github.com/lobovit/OLTN",
    "",
    "This repository is generated by `make publish`; do not edit it by hand.",
    "",
  ].join("\n"),
);

git(["add", "-A"]);
const status = git(["status", "--porcelain"], { stdio: "pipe", encoding: "utf8" }).trim();
if (!status) {
  console.log(`OK: nothing new to publish — ${SITE_URL} is up to date`);
  process.exit(0);
}

const stamp = new Date().toISOString().slice(0, 16).replace("T", " ");
git(["commit", "-m", `deploy: OLTN build ${stamp}`]);
console.log("> pushing");
git(["push", "origin", BRANCH]);
console.log(`OK: published — ${SITE_URL} (Pages rebuilds in about a minute)`);
